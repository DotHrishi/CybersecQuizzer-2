-- 7. CREATE USER PROFILES TABLE
-- Stores full name, nickname, email ID, and email type (college vs personal)
-- ==============================================================================
CREATE TABLE IF NOT EXISTS public.user_profiles (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    "fullName" TEXT NOT NULL,
    "nickname" TEXT NOT NULL UNIQUE,
    "isNicknameSame" BOOLEAN DEFAULT false,
    "email" TEXT NOT NULL,
    "emailType" VARCHAR(20) DEFAULT 'college', -- 'college' or 'personal'
    "createdAt" TIMESTAMPTZ DEFAULT NOW(),
    "updatedAt" TIMESTAMPTZ DEFAULT NOW()
);

-- Index for fast user profile lookups
CREATE INDEX IF NOT EXISTS idx_user_profiles_nickname ON public.user_profiles("nickname");
CREATE INDEX IF NOT EXISTS idx_user_profiles_email ON public.user_profiles("email");

-- Enable Row Level Security (RLS)
ALTER TABLE public.user_profiles ENABLE ROW LEVEL SECURITY;

-- ==============================================================================
-- 8. CREATE ADMIN USERS TABLE
-- Stores email, password hash, name, active status for authorized quiz admins
-- ==============================================================================
CREATE TABLE IF NOT EXISTS public.admin_users (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    "email" TEXT NOT NULL UNIQUE,
    "passwordHash" TEXT NOT NULL,
    "name" TEXT,
    "active" BOOLEAN DEFAULT true,
    "createdAt" TIMESTAMPTZ DEFAULT NOW(),
    "updatedAt" TIMESTAMPTZ DEFAULT NOW()
);

-- Index for fast admin user lookups by email
CREATE INDEX IF NOT EXISTS idx_admin_users_email ON public.admin_users("email");

-- Enable Row Level Security (RLS)
ALTER TABLE public.admin_users ENABLE ROW LEVEL SECURITY;

-- RLS Policy for Admin Users
DROP POLICY IF EXISTS "Enable all access for admin_users" ON public.admin_users;
CREATE POLICY "Enable all access for admin_users" 
ON public.admin_users FOR ALL 
TO anon, authenticated 
USING (true) 
WITH CHECK (true);

