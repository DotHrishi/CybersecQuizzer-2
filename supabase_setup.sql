-- 1. CREATE QUESTIONS TABLE
CREATE TABLE IF NOT EXISTS public.questions (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    "questionText" TEXT NOT NULL,
    "optionA" TEXT NOT NULL,
    "optionB" TEXT NOT NULL,
    "optionC" TEXT NOT NULL,
    "optionD" TEXT NOT NULL,
    "correctOption" VARCHAR(5) NOT NULL, -- 'A', 'B', 'C', or 'D'
    category VARCHAR(100) DEFAULT 'General Security',
    difficulty VARCHAR(50) DEFAULT 'Medium', -- 'Easy', 'Medium', 'Hard'
    active BOOLEAN DEFAULT true,
    "createdAt" TIMESTAMPTZ DEFAULT NOW(),
    "updatedAt" TIMESTAMPTZ DEFAULT NOW()
);

-- 2. CREATE USER ATTEMPTS TABLE
-- Privacy Mandate: ONLY stores userName, quizDate, isCorrect, score, bonusPoints, totalPoints, responseTimeMs, createdAt
-- DOES NOT store which question was answered or the user's selected option!
CREATE TABLE IF NOT EXISTS public.user_attempts (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    "userName" TEXT NOT NULL,
    "quizDate" VARCHAR(10) NOT NULL, -- Format: YYYY-MM-DD
    "isCorrect" BOOLEAN NOT NULL,
    score INT NOT NULL, -- Base score: 1 if correct, 0 if wrong
    "bonusPoints" INT NOT NULL, -- Speed bonus: 10, 8, 6, 4, 2, 1, 0
    "totalPoints" INT NOT NULL, -- score + bonusPoints
    "responseTimeMs" INT NOT NULL, -- Milliseconds taken to answer
    category TEXT DEFAULT 'General Security',
    "createdAt" TIMESTAMPTZ DEFAULT NOW()
);

-- Migration query if table already exists in Supabase
ALTER TABLE public.user_attempts ADD COLUMN IF NOT EXISTS category TEXT DEFAULT 'General Security';


-- 3. INDEXES FOR HIGH PERFORMANCE
CREATE INDEX IF NOT EXISTS idx_questions_active ON public.questions(active);
CREATE INDEX IF NOT EXISTS idx_user_attempts_username ON public.user_attempts("userName");
CREATE INDEX IF NOT EXISTS idx_user_attempts_quizdate ON public.user_attempts("quizDate");
CREATE INDEX IF NOT EXISTS idx_user_attempts_username_quizdate ON public.user_attempts("userName", "quizDate");
CREATE INDEX IF NOT EXISTS idx_user_attempts_total_points ON public.user_attempts("totalPoints" DESC, "responseTimeMs" ASC);

-- 4. ROW LEVEL SECURITY (RLS) POLICIES
ALTER TABLE public.questions ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.user_attempts ENABLE ROW LEVEL SECURITY;

-- Full CRUD Policy for Questions (Select, Insert, Update, Delete)
DROP POLICY IF EXISTS "Enable all access for questions" ON public.questions;
DROP POLICY IF EXISTS "Public can read active questions" ON public.questions;
CREATE POLICY "Enable all access for questions" 
ON public.questions FOR ALL 
TO anon, authenticated 
USING (true) 
WITH CHECK (true);

-- Full Access Policy for User Attempts
DROP POLICY IF EXISTS "Enable all access for user_attempts" ON public.user_attempts;
DROP POLICY IF EXISTS "Public can read user attempts" ON public.user_attempts;
DROP POLICY IF EXISTS "Public can submit quiz attempt" ON public.user_attempts;
CREATE POLICY "Enable all access for user_attempts" 
ON public.user_attempts FOR ALL 
TO anon, authenticated 
USING (true) 
WITH CHECK (true);

